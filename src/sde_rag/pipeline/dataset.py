"""The public dataset.

publish_data(): a consistent copy of the working database without local usage records and logs, and without
sources configured `publish = false` (for example sites that need a login), plus their raw files.
The database goes to a GitHub release (`rag.db.gz`; only the newest `release_keep` dataset releases are kept,
because every version stored in Git LFS would be kept forever); the raw files are content-addressed and live in
dataset/raw/ with Git LFS; dataset/MANIFEST.json names the release and the database checksum.
import_data(): start a fresh clone from the published dataset.
"""

import gzip
import hashlib
import json
import logging
import shutil
import sqlite3
import subprocess
from datetime import datetime, timezone
from pathlib import Path

import httpx

from sde_rag import db
from sde_rag.index.versions import active_version, version_info
from sde_rag.pipeline.stages import heat
from sde_rag.settings import ROOT, data_dir, section
from sde_rag.sources import source_configs

log = logging.getLogger("sde_rag.dataset")

# Local usage records and run logs: never published. The merge log keeps the dropped wordings' text, which
# may come from a source that is not published.
LOCAL_TABLES = ("query_logs", "alerts", "run_locks", "ingest_runs", "eval_runs", "question_merges", "agent_checks")
ASSET = "rag.db.gz"
TAG_PREFIX = "dataset-"

