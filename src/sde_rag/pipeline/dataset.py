"""The public dataset published with the repository (dataset/, stored with Git LFS).

publish_data(): a consistent copy of the working database without local usage records and logs, and without
sources configured `publish = false` (for example sites that need a login), plus their raw files.
import_data(): start a fresh clone from the published dataset.
"""

