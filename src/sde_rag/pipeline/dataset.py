"""The public dataset.

publish_data(): a consistent copy of the working database without local usage records and logs, and without
sources configured `publish = false` (for example sites that need a login), plus their raw files.
The database (`rag.db.gz`) and raw files (`raw.tar.gz`) go to the same GitHub release; only the newest
`release_keep` dataset releases are kept. Only the manifest and notices live in Git.
import_data(): start a fresh clone from the database; optionally download the raw files too.
"""

