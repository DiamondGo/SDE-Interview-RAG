def dataset_dir() -> Path:
    return ROOT / "dataset"


def unpublished_sources() -> set[str]:
    return {name for name, cfg in source_configs().items() if cfg.get("publish", True) is False}


def _drop_source(c: sqlite3.Connection, source: str) -> set[int]:
    """Delete one source's documents and everything derived from them. Returns the questions that lost mentions."""
    doc_ids = [r[0] for r in c.execute("SELECT id FROM documents WHERE source = ?", (source,))]
    touched: set[int] = set()
    for i in range(0, len(doc_ids), 500):
        ids = doc_ids[i:i + 500]
        marks = ",".join("?" * len(ids))
        touched |= {r[0] for r in c.execute(f"SELECT DISTINCT question_id FROM question_mentions WHERE doc_id IN ({marks})", ids)}
        c.execute(f"DELETE FROM question_mentions WHERE doc_id IN ({marks})", ids)
        chunk_ids = [r[0] for r in c.execute(f"SELECT id FROM chunks WHERE doc_id IN ({marks})", ids)]
        _drop_chunks(c, chunk_ids)
        c.execute(f"DELETE FROM documents WHERE id IN ({marks})", ids)
    c.execute("DELETE FROM seen_items WHERE source = ?", (source,))
    c.execute("DELETE FROM sources WHERE name = ?", (source,))
    return touched


def _drop_chunks(c: sqlite3.Connection, chunk_ids: list[int]) -> None:
    for i in range(0, len(chunk_ids), 500):
        ids = chunk_ids[i:i + 500]
        marks = ",".join("?" * len(ids))
        c.execute(f"DELETE FROM chunk_fts WHERE rowid IN ({marks})", ids)
        c.execute(f"DELETE FROM embeddings WHERE chunk_id IN ({marks})", ids)
        c.execute(f"DELETE FROM chunks WHERE id IN ({marks})", ids)


def _refresh_questions(c: sqlite3.Connection, qids: set[int]) -> int:
    """Recount questions that lost mentions; delete the ones left with none. Returns how many were deleted."""
    removed = 0
    now = datetime.now(timezone.utc)
    for qid in qids:
        r = c.execute("SELECT COUNT(*) AS n, COUNT(DISTINCT d.origin) AS origins, COUNT(DISTINCT m.company) AS cos, "
                      "MAX(COALESCE(d.published_at, d.fetched_at)) AS last FROM question_mentions m "
                      "JOIN documents d ON d.id = m.doc_id WHERE m.question_id = ?", (qid,)).fetchone()
        if not r[0]:
            _drop_chunks(c, [x[0] for x in c.execute("SELECT id FROM chunks WHERE question_id = ?", (qid,))])
            c.execute("DELETE FROM question_tags WHERE question_id = ?", (qid,))
            c.execute("DELETE FROM questions WHERE id = ?", (qid,))
            removed += 1
            continue
        days = (now - datetime.fromisoformat(r[3])).total_seconds() / 86400
        c.execute("UPDATE questions SET mention_count = ?, distinct_sources = ?, heat = ? WHERE id = ?",
                  (r[0], r[1], heat(r[1], r[2], r[0], days), qid))
    return removed


def publish_data(out: Path | None = None) -> dict:
    out = out or dataset_dir()
    out.mkdir(parents=True, exist_ok=True)
    src = db.conn()
    src.execute("PRAGMA wal_checkpoint(TRUNCATE)")
    tmp = out / "rag.db.tmp"
    tmp.unlink(missing_ok=True)
    src.execute("VACUUM INTO ?", (str(tmp),))

    c = sqlite3.connect(tmp, isolation_level=None)
    c.execute("PRAGMA journal_mode=DELETE")       # one self-contained file
    c.execute("BEGIN")
    for table in LOCAL_TABLES:
        c.execute(f"DELETE FROM {table}")
    dropped, touched = {}, set()
    for source in sorted(unpublished_sources()):
        n = c.execute("SELECT COUNT(*) FROM documents WHERE source = ?", (source,)).fetchone()[0]
        touched |= _drop_source(c, source)
        dropped[source] = n
    removed_questions = _refresh_questions(c, touched)
    c.execute("COMMIT")
    c.execute("VACUUM")
    counts = {
        "documents_by_source": dict(c.execute("SELECT source, COUNT(*) FROM documents GROUP BY source").fetchall()),
        "questions": c.execute("SELECT COUNT(*) FROM questions").fetchone()[0],
        "questions_by_category": {k or "none": v for k, v in c.execute(
            "SELECT category, COUNT(*) FROM questions GROUP BY category ORDER BY 2 DESC")},
        "chunks": c.execute("SELECT COUNT(*) FROM chunks").fetchone()[0],
        "embeddings": c.execute("SELECT COUNT(*) FROM embeddings").fetchone()[0],
    }
    raw_paths = {r[0] for r in c.execute("SELECT raw_path FROM documents WHERE raw_path IS NOT NULL")}
    leftovers = [t for t in LOCAL_TABLES if c.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]]
    c.close()
    if leftovers:
        tmp.unlink()
        raise RuntimeError(f"local tables still hold rows: {leftovers}")
    tmp.replace(out / "rag.db")

    # Raw files: exactly the ones the published documents reference.
    raw_out = out / "raw"
    wanted = {out / p for p in raw_paths}
    copied = 0
    for p in raw_paths:
        dst = out / p
        if not dst.exists():
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(data_dir() / p, dst)
            copied += 1
    stale = [f for f in raw_out.rglob("*.gz") if f not in wanted] if raw_out.exists() else []
    for f in stale:
        f.unlink()

    version = active_version()
    info = version_info(version)
    manifest = {"generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                "index_version": version, "embed_model": info["embed_model"] if info else None,
                "unpublished_sources": dropped, "questions_removed_with_them": removed_questions,
                "raw_files": len(raw_paths), **counts}
    (out / "MANIFEST.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=1) + "\n")
    (out / "NOTICE.md").write_text(NOTICE_EN)
    (out / "NOTICE.zh-CN.md").write_text(NOTICE_ZH)
    log.info("published dataset: %s", manifest)
    return {**manifest, "raw_copied": copied, "raw_removed": len(stale)}


def import_data(force: bool = False) -> dict:
    """Copy dataset/ into data/ as a starting point. Refuses to overwrite a working database unless force."""
    src = dataset_dir()
    if not (src / "rag.db").is_file():
        raise FileNotFoundError(f"{src / 'rag.db'} not found (is Git LFS installed? run `git lfs pull`)")
    if (src / "rag.db").stat().st_size < 1024 and (src / "rag.db").read_bytes().startswith(b"version https://git-lfs"):
        raise RuntimeError("dataset/rag.db is a Git LFS pointer: install Git LFS and run `git lfs pull`")
    dst = data_dir() / "rag.db"
    if dst.exists() and not force:
        raise FileExistsError(f"{dst} exists; use --force to replace it")
    db.close_all()
    for suffix in ("", "-wal", "-shm"):
        Path(f"{dst}{suffix}").unlink(missing_ok=True)
    shutil.copy2(src / "rag.db", dst)
    n = 0
    for f in (src / "raw").rglob("*.gz") if (src / "raw").exists() else []:
        target = data_dir() / f.relative_to(src)
        if not target.exists():
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, target)
            n += 1
    shutil.rmtree(data_dir() / "index", ignore_errors=True)   # the vector snapshot is rebuilt from the database
    return {"database": str(dst), "raw_files": n}
