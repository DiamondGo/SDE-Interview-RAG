def dataset_dir() -> Path:
    return ROOT / "dataset"


def unpublished_sources() -> set[str]:
    return {name for name, cfg in source_configs().items() if cfg.get("publish", True) is False}


def _drop_source(c: sqlite3.Connection, source: str) -> set[int]:
    """Delete one source's documents and everything derived from them. Returns the questions that lost mentions."""
    doc_ids = [r[0] for r in c.execute("SELECT id FROM documents WHERE source = ?", (source,))]
    touched: set[int] = set()
    for i in range(0, len(doc_ids), 500):
        ids = doc_ids[i:i + 500]
        marks = ",".join("?" * len(ids))
        touched |= {r[0] for r in c.execute(f"SELECT DISTINCT question_id FROM question_mentions WHERE doc_id IN ({marks})", ids)}
        c.execute(f"DELETE FROM question_mentions WHERE doc_id IN ({marks})", ids)
        chunk_ids = [r[0] for r in c.execute(f"SELECT id FROM chunks WHERE doc_id IN ({marks})", ids)]
        _drop_chunks(c, chunk_ids)
        c.execute(f"DELETE FROM documents WHERE id IN ({marks})", ids)
    c.execute("DELETE FROM seen_items WHERE source = ?", (source,))
    c.execute("DELETE FROM sources WHERE name = ?", (source,))
    return touched


def _drop_chunks(c: sqlite3.Connection, chunk_ids: list[int]) -> None:
    for i in range(0, len(chunk_ids), 500):
        ids = chunk_ids[i:i + 500]
        marks = ",".join("?" * len(ids))
        c.execute(f"DELETE FROM chunk_fts WHERE rowid IN ({marks})", ids)
        c.execute(f"DELETE FROM embeddings WHERE chunk_id IN ({marks})", ids)
        c.execute(f"DELETE FROM chunks WHERE id IN ({marks})", ids)


def _refresh_questions(c: sqlite3.Connection, qids: set[int]) -> int:
    """Recount questions that lost mentions; delete the ones left with none. Returns how many were deleted."""
    removed = 0
    now = datetime.now(timezone.utc)
    for qid in qids:
        r = c.execute("SELECT COUNT(*) AS n, COUNT(DISTINCT d.origin) AS origins, COUNT(DISTINCT m.company) AS cos, "
                      "MAX(COALESCE(d.published_at, d.fetched_at)) AS last FROM question_mentions m "
                      "JOIN documents d ON d.id = m.doc_id WHERE m.question_id = ?", (qid,)).fetchone()
        if not r[0]:
            _drop_chunks(c, [x[0] for x in c.execute("SELECT id FROM chunks WHERE question_id = ?", (qid,))])
            c.execute("DELETE FROM question_tags WHERE question_id = ?", (qid,))
            c.execute("DELETE FROM question_vectors WHERE question_id = ?", (qid,))
            c.execute("DELETE FROM question_aliases WHERE question_id = ?", (qid,))
            c.execute("DELETE FROM dedup_pairs WHERE a = ? OR b = ?", (qid, qid))
            c.execute("DELETE FROM questions WHERE id = ?", (qid,))
            removed += 1
            continue
        days = (now - datetime.fromisoformat(r[3])).total_seconds() / 86400
        c.execute("UPDATE questions SET mention_count = ?, distinct_sources = ?, heat = ? WHERE id = ?",
                  (r[0], r[1], heat(r[1], r[2], r[0], days), qid))
    return removed


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def _gh(*args: str) -> str:
    """Run the GitHub CLI (it uses its own login; nothing here handles credentials)."""
    return subprocess.run(["gh", *args], check=True, capture_output=True, text=True).stdout


def release_repo() -> str:
    repo = section("dataset").get("release_repo")
    if not repo:
        raise RuntimeError("set [dataset] release_repo (owner/name) in config/settings.local.toml")
    return repo


def upload_release(db_path: Path, manifest: dict) -> dict:
    """Upload the gzipped database as a new release, then delete dataset releases beyond `release_keep`."""
    repo, keep = release_repo(), max(1, int(section("dataset").get("release_keep", 3)))
    gz = db_path.with_name(ASSET)
    with open(db_path, "rb") as f, gzip.open(gz, "wb", compresslevel=6) as g:
        shutil.copyfileobj(f, g, 1 << 20)
    tag = TAG_PREFIX + datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    notes = (f"Database for `sde-rag import-data`: {manifest['questions']} questions, {manifest['chunks']} chunks, "
             f"embeddings from `{manifest['embed_model']}`. Content belongs to its authors; see dataset/NOTICE.md.")
    _gh("release", "create", tag, str(gz), "--repo", repo, "--title", f"Dataset {tag[len(TAG_PREFIX):]}",
        "--notes", notes)
    releases = json.loads(_gh("release", "list", "--repo", repo, "--limit", "100", "--json", "tagName,createdAt"))
    ours = sorted((r for r in releases if r["tagName"].startswith(TAG_PREFIX)), key=lambda r: r["createdAt"],
                  reverse=True)
    deleted = []
    for r in ours[keep:]:
        if r["tagName"] != tag:
            _gh("release", "delete", r["tagName"], "--repo", repo, "--yes", "--cleanup-tag")
            deleted.append(r["tagName"])
    return {"release": tag, "asset": ASSET, "asset_sha256": _sha256(gz), "asset_bytes": gz.stat().st_size,
            "url": f"https://github.com/{repo}/releases/download/{tag}/{ASSET}", "releases_deleted": deleted}


def publish_data(out: Path | None = None, *, upload: bool = True) -> dict:
    out = out or dataset_dir()
    out.mkdir(parents=True, exist_ok=True)
    src = db.conn()
    src.execute("PRAGMA wal_checkpoint(TRUNCATE)")
    tmp = out / "rag.db.tmp"
    tmp.unlink(missing_ok=True)
    src.execute("VACUUM INTO ?", (str(tmp),))

    c = sqlite3.connect(tmp, isolation_level=None)
    c.execute("PRAGMA journal_mode=DELETE")       # one self-contained file
    c.execute("BEGIN")
    for table in LOCAL_TABLES:
        c.execute(f"DELETE FROM {table}")
    # Reviews of query answers hold the questions people asked; reviews of source answers are bank data.
    c.execute("DELETE FROM review_jobs WHERE kind != 'source_answer' OR status != 'done'")
    dropped, touched = {}, set()
    for source in sorted(unpublished_sources()):
        n = c.execute("SELECT COUNT(*) FROM documents WHERE source = ?", (source,)).fetchone()[0]
        touched |= _drop_source(c, source)
        dropped[source] = n
    removed_questions = _refresh_questions(c, touched)
    c.execute("DELETE FROM review_jobs WHERE subject_id NOT IN (SELECT id FROM questions)")
    c.execute("COMMIT")
    c.execute("VACUUM")
    counts = {
        "documents_by_source": dict(c.execute("SELECT source, COUNT(*) FROM documents GROUP BY source").fetchall()),
        "questions": c.execute("SELECT COUNT(*) FROM questions").fetchone()[0],
        "questions_by_category": {k or "none": v for k, v in c.execute(
            "SELECT category, COUNT(*) FROM questions GROUP BY category ORDER BY 2 DESC")},
        "chunks": c.execute("SELECT COUNT(*) FROM chunks").fetchone()[0],
        "embeddings": c.execute("SELECT COUNT(*) FROM embeddings").fetchone()[0],
    }
    raw_paths = {r[0] for r in c.execute("SELECT raw_path FROM documents WHERE raw_path IS NOT NULL")}
    leftovers = [t for t in LOCAL_TABLES if c.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]]
    if c.execute("SELECT COUNT(*) FROM review_jobs WHERE kind != 'source_answer'").fetchone()[0]:
        leftovers.append("review_jobs (query answers)")
    c.close()
    if leftovers:
        tmp.unlink()
        raise RuntimeError(f"local tables still hold rows: {leftovers}")
    tmp.replace(out / "rag.db")

    # Raw files: exactly the ones the published documents reference.
    raw_out = out / "raw"
    wanted = {out / p for p in raw_paths}
    copied = 0
    for p in raw_paths:
        dst = out / p
        if not dst.exists():
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(data_dir() / p, dst)
            copied += 1
    stale = [f for f in raw_out.rglob("*.gz") if f not in wanted] if raw_out.exists() else []
    for f in stale:
        f.unlink()

    version = active_version()
    info = version_info(version)
    manifest = {"generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                "index_version": version, "embed_model": info["embed_model"] if info else None,
                "unpublished_sources": dropped, "questions_removed_with_them": removed_questions,
                "raw_files": len(raw_paths), **counts}
    db_file = out / "rag.db"
    database = {"file": "rag.db", "sha256": _sha256(db_file), "bytes": db_file.stat().st_size, "release": None}
    deleted: list[str] = []
    if upload:
        rel = upload_release(db_file, manifest)
        deleted = rel.pop("releases_deleted")
        database.update(rel)
    manifest["database"] = database
    (out / "MANIFEST.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=1) + "\n")
    (out / "NOTICE.md").write_text(NOTICE_EN)
    (out / "NOTICE.zh-CN.md").write_text(NOTICE_ZH)
    log.info("published dataset: %s", manifest)
    return {**manifest, "raw_copied": copied, "raw_removed": len(stale), "releases_deleted": deleted}


def _download(url: str, dst: Path) -> None:
    with httpx.stream("GET", url, follow_redirects=True, timeout=httpx.Timeout(60, read=300)) as r:
        r.raise_for_status()
        with open(dst, "wb") as f:
            for block in r.iter_bytes(1 << 20):
                f.write(block)


def _lfs_pointer(path: Path) -> bool:
    with open(path, "rb") as f:
        return f.read(40).startswith(b"version https://git-lfs")


def _published_db(src: Path) -> Path:
    """dataset/rag.db when it matches MANIFEST.json, otherwise the release download (checked against both)."""
    manifest = json.loads((src / "MANIFEST.json").read_text()) if (src / "MANIFEST.json").is_file() else {}
    info = manifest.get("database") or {}
    local = src / "rag.db"
    if local.is_file() and not _lfs_pointer(local) and (
            not info.get("sha256") or _sha256(local) == info["sha256"]):
        return local
    if not info.get("url"):
        raise FileNotFoundError("dataset/MANIFEST.json names no published database release")
    tmp_dir = data_dir() / "download"
    tmp_dir.mkdir(parents=True, exist_ok=True)
    gz, out = tmp_dir / f"{ASSET}.part", tmp_dir / "rag.db.part"
    log.info("downloading %s", info["url"])
    _download(info["url"], gz)
    if info.get("asset_sha256") and _sha256(gz) != info["asset_sha256"]:
        raise RuntimeError(f"checksum mismatch for {info['url']}")
    with gzip.open(gz, "rb") as g, open(out, "wb") as f:
        shutil.copyfileobj(g, f, 1 << 20)
    gz.unlink()
    if _sha256(out) != info["sha256"]:
        raise RuntimeError("the downloaded database does not match dataset/MANIFEST.json")
    return out


def import_data(force: bool = False) -> dict:
    """Start data/ from the published dataset. Refuses to overwrite a working database unless force."""
    src = dataset_dir()
    dst = data_dir() / "rag.db"
    if dst.exists() and not force:
        raise FileExistsError(f"{dst} exists; use --force to replace it")
    raw = [f for f in (src / "raw").rglob("*.gz")] if (src / "raw").exists() else []
    if raw and _lfs_pointer(raw[0]):
        raise RuntimeError("dataset/raw holds Git LFS pointers: install Git LFS and run `git lfs pull`")
    published = _published_db(src)
    db.close_all()
    for suffix in ("", "-wal", "-shm"):
        Path(f"{dst}{suffix}").unlink(missing_ok=True)
    if published.parent == src:
        shutil.copy2(published, dst)
    else:
        published.replace(dst)
    n = 0
    for f in raw:
        target = data_dir() / f.relative_to(src)
        if not target.exists():
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, target)
            n += 1
    shutil.rmtree(data_dir() / "index", ignore_errors=True)   # the vector snapshot is rebuilt from the database
    return {"database": str(dst), "raw_files": n}
